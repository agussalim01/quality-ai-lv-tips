import streamlit as st
import pandas as pd
import plotly.express as px
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
import io
import re
from datetime import datetime

st.set_page_config(page_title="Quality AI PRO", page_icon="📄", layout="wide")

def ai_beautify_steps(raw_text):
    lines = [l.strip() for l in re.split(r'\n|\d+\.', raw_text) if l.strip()]
    steps = []
    for i, line in enumerate(lines, 1):
        lower = line.lower()
        tool = "Jig LV, Obeng Torsi 5Nm" if "baut" in lower or "kencang" in lower else "Tangan / Jig"
        if "bocor" in lower or "cek" in lower: tool = "Air Sabun / Pressure Gauge"
        quality = "Pastikan posisi tip center" if "pasang" in lower else "Tidak ada kebocoran"
        safety = "Pakai Sarung Tangan" if "pasang" in lower or "tajam" in lower else "Pakai Kacamata Safety"
        baku = line.capitalize()
        if not baku.endswith('.'): baku += "."
        steps.append({"no": i, "deskripsi": baku, "tool": tool, "quality_point": quality, "safety_point": safety})
    return steps

def fill_template_doc(template_file, product, part_no, process, steps):
    doc = Document(template_file)
    placeholders = {
        "{{PRODUCT}}": product, "{{PART_NO}}": part_no,
        "{{PROCESS}}": process, "{{DATE}}": datetime.now().strftime("%d-%m-%Y"),
        "{{PRODUCT_NAME}}": product,
    }
    for p in doc.paragraphs:
        for k,v in placeholders.items():
            if k in p.text: p.text = p.text.replace(k, v)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for k,v in placeholders.items():
                    if k in cell.text: cell.text = cell.text.replace(k, v)
    
    doc.add_paragraph("")
    title = doc.add_paragraph()
    run = title.add_run(f"WORK INSTRUCTION - {product} (AI Generated)")
    run.bold = True
    run.font.size = Pt(12)
    
    # BUAT TABEL TANPA STYLE - ANTI ERROR
    table = doc.add_table(rows=1, cols=5)
    hdr = table.rows[0].cells
    hdr[0].text = 'No'
    hdr[1].text = 'Langkah Kerja'
    hdr[2].text = 'Tools'
    hdr[3].text = 'Quality Point'
    hdr[4].text = 'Safety Point'
    
    for s in steps:
        row = table.add_row().cells
        row[0].text = str(s['no'])
        row[1].text = s['deskripsi']
        row[2].text = s['tool']
        row[3].text = s['quality_point']
        row[4].text = s['safety_point']
    
    doc.add_paragraph("")
    p = doc.add_paragraph(f"Generated by Quality AI PRO | Part: {part_no}")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return doc

st.title("📄 Quality AI PRO - MSA + WI Generator")
tab1, tab2 = st.tabs(["📊 MSA Dashboard", "📄 WI Generator (Template)"])

with tab1:
    st.subheader("MSA Dashboard")
    st.info("Dashboard aktif")
    data = pd.DataFrame({"Trial":[1,2,3],"Measurement":[10.1,10.2,10.0]})
    st.plotly_chart(px.histogram(data, x="Measurement"))

with tab2:
    st.subheader("Mode B: Ketik Kasar -> Jadi WI Resmi .docx")
    col1, col2 = st.columns(2)
    with col1:
        template_file = st.file_uploader("1. Upload Template WI (.docx)", type=["docx"])
        product = st.text_input("2. Nama Produk", "LV Tips Type A")
        part_no = st.text_input("3. No Part", "LV-TIPS-001")
    with col2:
        process = st.text_input("Nama Proses", "Assembling LV Tips")
        raw_steps = st.text_area("4. Langkah kasar:", "pasang tip LV ke housing\nkencengin baut 5Nm\ncek bocor pakai air sabun\nlap bersih dan packing", height=150)
    
    if st.button("✨ Generate WI dengan AI + Template", type="primary", use_container_width=True):
        if not template_file: st.error("Upload template dulu!")
        elif not raw_steps: st.error("Isi langkah kasar!")
        else:
            with st.spinner("AI merapikan..."):
                steps = ai_beautify_steps(raw_steps)
                final_doc = fill_template_doc(template_file, product, part_no, process, steps)
                bio = io.BytesIO()
                final_doc.save(bio)
                bio.seek(0)
                st.success(f"Berhasil! {len(steps)} langkah jadi!")
                st.dataframe(pd.DataFrame(steps), use_container_width=True)
                st.download_button("📥 Download WI Final (.docx)", data=bio, file_name=f"WI_{part_no}.docx", mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document", use_container_width=True)
