# --- AI LOGIC UNTUK MERAPIKAN LANGKAH KASAR ---
def ai_beautify_steps(raw_text):
    # Pecah berdasarkan enter atau nomor
    lines = [l.strip() for l in re.split(r'\n|\d+\.', raw_text) if l.strip()]
    steps = []
    for i, line in enumerate(lines, 1):
        lower = line.lower()
        tool = "Jig LV, Obeng Torsi 5Nm" if "baut" in lower or "kencang" in lower else "Tangan / Jig"
        if "bocor" in lower or "cek" in lower: tool = "Air Sabun / Pressure Gauge"
        
        quality = "Pastikan posisi tip center" if "pasang" in lower else "Tidak ada kebocoran"
        safety = "Pakai Sarung Tangan" if "pasang" in lower or "tajam" in lower else "Pakai Kacamata Safety"
        
        # Buat kalimat baku WI
        baku = line.capitalize()
        if not baku.endswith('.'): baku += "."
        if "cek" in lower: baku = baku.replace("cek", "Periksa")
        
        steps.append({
            "no": i,
            "deskripsi": baku,
            "tool": tool,
            "quality_point": quality,
            "safety_point": safety
        })
    return steps

def fill_template_doc(template_file, product, part_no, process, steps):
    doc = Document(template_file)
    
    # 1. Ganti placeholder di paragraf
    placeholders = {
        "{{PRODUCT}}": product,
        "{{PART_NO}}": part_no,
        "{{PROCESS}}": process,
        "{{DATE}}": datetime.now().strftime("%d-%m-%Y"),
        "{{PRODUCT_NAME}}": product,
    }
    
    for p in doc.paragraphs:
        for key, val in placeholders.items():
            if key in p.text:
                p.text = p.text.replace(key, val)
    
    # Juga di tabel (kalau template punya header tabel)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for key, val in placeholders.items():
                    if key in cell.text:
                        cell.text = cell.text.replace(key, val)

    # 2. Tambahkan Tabel WI Baru (AI Generated)
    doc.add_paragraph("")
    title = doc.add_paragraph()
    title_run = title.add_run(f"WORK INSTRUCTION - {product} (AI Generated)")
    title_run.bold = True
    title_run.font.size = Pt(12)
    
    table = doc.add_table(rows=1, cols=5)
    table.style = 'Light Shading'
    hdr = table.rows[0].cells
    hdr[0].text = 'No'
    hdr[1].text = 'Langkah Kerja (Baku)'
    hdr[2].text = 'Tools'
    hdr[3].text = 'Quality Point'
    hdr[4].text = 'Safety Point'
    
    for s in steps:
        row = table.add_row().cells
        row[0].text = str(s['no'])
        row[1].text = s['deskripsi']
        row[2].text = s['tool']
        row[3].text = s['quality_point']
        row[4].text = s['safety_point']
    
    # Footer
    doc.add_paragraph("")
    p = doc.add_paragraph(f"Generated by Quality AI PRO | Part: {part_no} | Date: {placeholders['{{DATE}}']}")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    return doc

