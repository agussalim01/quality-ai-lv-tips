st.set_page_config(page_title="Quality AI PRO - WI NT8", layout="wide")

def parse_raw_steps(raw):
    # Pisah step berdasarkan enter
    lines = [l.strip() for l in raw.split('\n') if l.strip()]
    parsed = []
    current_step_title = ""
    current_bullets = []
    
    for line in lines:
        # Jika ada kata Step atau mengandung : anggap judul step
        if re.match(r'^(Step\s*\d+|Susun|Check|Data|Packing|Manual|Ionizer)', line, re.I):
            if current_step_title or current_bullets:
                parsed.append({"title": current_step_title, "bullets": current_bullets})
            current_step_title = line
            current_bullets = []
        else:
            # hilangkan bullet lama
            clean = re.sub(r'^[•\-\*]\s*', '', line)
            current_bullets.append(clean)
    if current_step_title or current_bullets:
        parsed.append({"title": current_step_title, "bullets": current_bullets})
    return parsed

def create_wi_nt8(doc_no, product, temp_no, rev, process_desc, part_req, tools_req, steps_data, time_summary):
    doc = Document()
    
    # --- HEADER TABLE (mirip WIN kamu) ---
    header_table = doc.add_table(rows=4, cols=4)
    header_table.autofit = True
    # Row 0
    header_table.cell(0,0).text = "WORK INSTRUCTION"
    header_table.cell(0,1).text = f"Revision No.\n{rev}"
    header_table.cell(0,2).text = f"Document No.\n{doc_no}"
    header_table.cell(0,3).text = f"Product\n{product}"
    # Row 1
    header_table.cell(1,0).text = ""
    header_table.cell(1,1).text = ""
    header_table.cell(1,2).text = f"Temp. Number : {temp_no}"
    header_table.cell(1,3).text = f"Release Date\n{datetime.now().strftime('%d/%m/%Y')}"
    # Row 2
    header_table.cell(2,0).merge(header_table.cell(2,3)).text = f"Process Desc.\n{process_desc}"
    # Row 3
    header_table.cell(3,0).merge(header_table.cell(3,3)).text = "Work Instruction"

    for row in header_table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(8)
                    r.bold = True

    doc.add_paragraph("")
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run(f"{process_desc}\n{product}")
    run.bold = True
    run.font.size = Pt(14)

    # --- TABEL RINGKASAN WAKTU (seperti Page 1 contoh kamu) ---
    doc.add_paragraph("Langkah Kerja", style='Heading 2')
    summary_table = doc.add_table(rows=1, cols=3)
    summary_table.rows[0].cells[0].text = "Langkah Kerja"
    summary_table.rows[0].cells[1].text = "Time (min)"
    summary_table.rows[0].cells[2].text = "Total"
    
    total = 0
    for item in time_summary:
        row = summary_table.add_row().cells
        row[0].text = item['step']
        row[1].text = str(item['time'])
        row[2].text = ""
        total += int(item['time']) if str(item['time']).isdigit() else 0
    last = summary_table.add_row().cells
    last[0].text = "Total"
    last[1].text = str(total)
    
    doc.add_paragraph("")
    
    # --- PART & TOOLS (Page 2 contoh kamu) ---
    doc.add_paragraph(f"Part required :", style='Heading 3')
    for p in part_req.split('\n'):
        if p.strip(): doc.add_paragraph(f"● {p.strip()}", style='List Bullet')
        
    doc.add_paragraph(f"Tools required :", style='Heading 3')
    for t in tools_req.split('\n'):
        if t.strip(): doc.add_paragraph(f"● {t.strip()}", style='List Bullet')

    # --- DETAIL STEP ---
    for idx, step in enumerate(steps_data, 1):
        title_text = step['title'] if step['title'] else f"Step {idx}"
        doc.add_paragraph(f"{title_text}", style='Heading 2')
        for bullet in step['bullets']:
            doc.add_paragraph(f"● {bullet}", style='List Bullet')
        doc.add_paragraph("") # spasi

    # Footer page
    doc.add_paragraph(f"Page 1 of {len(steps_data)+2} | Generated by Quality AI PRO")
    
    return doc

